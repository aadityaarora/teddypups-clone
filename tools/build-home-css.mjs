// Generate app/styles/home.css: home-section rules from the original CSS, grouped per section
// usage: node tools/build-home-css.mjs
// Each group = tools/pick-css.mjs <regex> --auto-keyframes --pretty. Rules/keyframes already emitted
// (by an earlier group or by app/styles/chrome.css) are skipped so nothing is duplicated.
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';

const GROUPS = [
  ['Meet the pups', 'Arched doors per puppy. Grid by default; on desktop with motion the section pins and the\n   doors slide past on a treadmill (data-pinned, Meet.tsx).', String.raw`\.tp-(meet|door(?!s))`],
  ['Two ways to meet your puppy', 'Signpost: showroom window over the Dubai skyline (left) and a plane flying Korea -> Dubai (right).', String.raw`\.tp-(paths|fork|way(?!s)|sign|window|flight)`],
  ['Your puppy journey', 'Numbered steps next to a WhatsApp-style phone; messages appear as each step scrolls in (Chat.tsx).', String.raw`\.tp-(chat|chips|clip|msg|phone|route|snaps|typing)`],
  ['Why families trust TeddyPups', 'Open puppy passport with ink stamps, then a city skyline at sunset.', String.raw`\.tp-(trust|book|entry|horizon|passport|stamp)`],
  ['Happy families', 'Testimonial speech bubble, then a wall of taped polaroids on a house front with a lamp, door and Teddy.', String.raw`\.tp-(dusk|facade|lamp|photowall|polaroid|street|tape)`],
  ['Questions answered', 'Night sky with stars; the first three FAQs as a static question/answer list beside a puzzled Teddy.', String.raw`\.tp-(night|qa)`],
  ['Photo viewer', 'Full-screen dialog opened from the family photo wall (PhotoViewer.tsx): blurry first paint, then the sharp image fades in.', String.raw`\.tp-viewer`],
  ['Welcome home (final CTA)', 'Little house with an opening door, a puppy photo inside and Teddy bowing.', String.raw`\.tp-(home|house)`],
];

const chrome = fs.readFileSync('app/styles/chrome.css', 'utf8');
const key = (block) => block.replace(/\s+/g, '');
const seen = new Set();
// flat rules already in chrome.css (compared whole, whitespace-insensitive)
for (const m of chrome.replace(/\/\*[\s\S]*?\*\//g, '').matchAll(/[^{}]+\{[^{}]*\}/g)) seen.add(key(m[0]));
for (const m of chrome.matchAll(/@keyframes\s+([\w-]+)/g)) seen.add('@kf:' + m[1]);

let out = `/*
 * Home page sections below the hero.
 * Generated by tools/build-home-css.mjs from the reference site's compiled CSS
 * (recon/css/10jf32vdx50lp.css). Values are the originals; edit the generator, not this file.
 *
 * Sections
${GROUPS.map(([t], i) => ` *   ${i + 1}. ${t}`).join('\n')}
 */
`;

GROUPS.forEach(([title, note, re], i) => {
  const css = execFileSync('node', ['tools/pick-css.mjs', re, '--auto-keyframes', '--pretty'], { encoding: 'utf8' });
  // split into top-level blocks (blank-line separated by --pretty)
  const blocks = css.split(/\n\n(?=\S)/).map((b) => b.trimEnd()).filter(Boolean);
  const kept = blocks.filter((b) => {
    const kf = b.match(/^@keyframes\s+([\w-]+)/);
    const k = kf ? '@kf:' + kf[1] : key(b);
    if (seen.has(k)) return false;
    seen.add(k);
    return true;
  });
  out += `\n\n/* ${i + 1}. ${title} ${'-'.repeat(Math.max(4, 74 - title.length))}\n   ${note} */\n\n${kept.join('\n\n')}\n`;
  console.log(`${title}: ${kept.length} blocks (${blocks.length - kept.length} duplicates skipped)`);
});

fs.writeFileSync('app/styles/home.css', out);
console.log('wrote app/styles/home.css', out.length, 'chars');
