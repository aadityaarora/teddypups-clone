// Generate typed data in lib/data/ from the recon RSC payloads
// usage: node tools/extract-data.mjs
// Writes lib/data/puppies.ts, testimonials.ts, faqs.ts (site.ts is hand-written from recon/html)

import fs from 'node:fs/promises';

const RSC = 'recon/rsc';
const read = (f) => fs.readFile(`${RSC}/${f}.txt`, 'utf8');

// Parse the JSON value (object/array) that starts at index i, respecting strings
function jsonAt(s, i) {
  const open = s[i], close = open === '[' ? ']' : '}';
  let depth = 0, inStr = false;
  for (let j = i; j < s.length; j++) {
    const c = s[j];
    if (inStr) { if (c === '\\') j++; else if (c === '"') inStr = false; continue; }
    if (c === '"') inStr = true;
    else if (c === open) depth++;
    else if (c === close && --depth === 0) return JSON.parse(s.slice(i, j + 1));
  }
  throw new Error('unterminated JSON at ' + i);
}
const valueAfter = (s, key, from = 0) => {
  const i = s.indexOf(key, from);
  return i < 0 ? undefined : jsonAt(s, i + key.length);
};
// text children of the first element whose className contains cls
const textOf = (s, re) => s.match(re)?.[1];

const media = (m) => m && ({
  id: m.id, url: m.url, kind: m.kind, width: m.width, height: m.height, alt: m.alt,
  ...(m.caption ? { caption: m.caption } : {}),
  focalX: m.focalX, focalY: m.focalY, color: m.color,
  ...(m.blurDataUrl ? { blurDataUrl: m.blurDataUrl } : {}),
  ...(m.durationS ? { durationS: m.durationS } : {}),
  ...(m.poster ? { poster: media(m.poster) } : {}),
});

// ---------- Puppies ----------
const listing = valueAfter(await read('puppies'), '"puppies":');
const bySlug = new Map(listing.map((p) => [p.slug, p]));

const files = (await fs.readdir(RSC)).filter((f) => f.startsWith('puppies__'));
const puppies = [];
for (const f of files.sort()) {
  const slug = f.slice('puppies__'.length, -4);
  const s = await read(f.slice(0, -4));
  const gallery = valueAfter(s, '"media":', s.indexOf('{"name":'));
  const facts = Object.fromEntries([...s.matchAll(/\["\$","div","([^"]+)",\{"children":\[\["\$","dt",null,\{[^}]*"children":"[^"]*"\}\],\["\$","dd",null,\{[^}]*"children":"([^"]*)"\}\]/g)].map((m) => [m[1], m[2]]));
  // the page h1 is "font-plush mt-4 ..." (an earlier font-plush h1 belongs to the embedded 404 template)
  const name = textOf(s, /\["\$","h1",null,\{"className":"font-plush mt-4[^"]*","children":"([^"]*)"/);
  const chip = textOf(s, /uppercase tracking-wide -rotate-6[^"]*","style":"[^"]*","children":"([^"]+)"/);
  const subtitle = textOf(s, /"h1",null,\{"className":"font-plush mt-4[^"]*","children":"[^"]*"\}\],\["\$","p",null,\{"className":"[^"]*","children":"([^"]*)"/);
  const seo = textOf(s, /\["\$","meta","1",\{"name":"description","content":"([^"]*)"/);
  const id = textOf(s, /"puppy":\{"id":"([^"]+)"/);
  const l = bySlug.get(slug);
  const status = l?.status ?? (/gone home/i.test(chip ?? '') ? 'gone-home' : 'unknown');
  const where = facts['Where'];
  puppies.push({
    id: id ?? l?.id,
    slug,
    name: l ? l.name : name,
    displayName: l?.displayName ?? name,
    breed: l?.breed ?? facts['Breed'] ?? subtitle,
    // "Boy or girl" is sometimes a lazy $L reference; the meta description always has it ("Pomsky, boy, 3 months old")
    gender: l?.gender ?? (/, girl,/.test(seo) ? 'female' : 'male'),
    genderLabel: l?.genderLabel ?? facts['Boy or girl'] ?? (/, girl,/.test(seo) ? 'Girl' : 'Boy'),
    age: l?.age ?? facts['Age'],
    origin: l?.origin?.slug ?? (/import/i.test(where ?? '') ? 'imported' : 'local'),
    originLabel: where,
    status: status === 'available' ? 'available' : status === 'gone-home' ? 'gone-home' : status,
    statusLabel: chip,
    breeds: l?.breeds ?? [],
    seoDescription: seo,
    cover: media(l?.cover ?? gallery.find((m) => m.kind === 'image')),
    images: gallery.filter((m) => m.kind === 'image').map(media),
    video: gallery.filter((m) => m.kind === 'video').map(media),
    media: gallery.map(media),
  });
}

// keep the listing order for available, then gone-home in recon order
const order = new Map(listing.map((p, i) => [p.slug, i]));
const goneOrder = [...(await read('gone-home')).matchAll(/"href":"\/puppies\/([^"]+)","className":"tp-ticket__link"/g)].map((m) => m[1]);
const rank = (p) => order.get(p.slug) ?? 1000 + (goneOrder.indexOf(p.slug) + 1 || 999);
puppies.sort((a, b) => rank(a) - rank(b));

const statusCounts = puppies.reduce((o, p) => ((o[p.status] = (o[p.status] || 0) + 1), o), {});
console.log('puppies', puppies.length, statusCounts, 'with video:', puppies.filter((p) => p.video.length).map((p) => p.slug).join(', '));
const missing = puppies.filter((p) => !p.breed || !p.age || !p.images.length);
if (missing.length) console.warn('incomplete:', missing.map((p) => p.slug));

const ts = (v) => JSON.stringify(v, null, 2);
const header = '// Generated by tools/extract-data.mjs from recon/rsc. Do not edit by hand.\n';

await fs.mkdir('lib/data', { recursive: true });
await fs.writeFile('lib/data/puppies.ts', `${header}
export type Media = {
  id: string;
  url: string;
  kind: "image" | "video";
  width: number;
  height: number;
  alt: string;
  caption?: string;
  focalX: number;
  focalY: number;
  color: string;
  blurDataUrl?: string;
  durationS?: number;
  poster?: Media;
};

export type PuppyStatus = "available" | "gone-home";
export type Origin = "local" | "imported";

export type Puppy = {
  id: string;
  slug: string;
  /** Pet name, empty when the puppy is listed by breed only */
  name: string;
  displayName: string;
  breed: string;
  gender: "male" | "female" | "male-female";
  genderLabel: "Boy" | "Girl" | "Boy & girl";
  age: string;
  origin: Origin;
  /** "Where" fact on the detail page */
  originLabel: string;
  status: PuppyStatus;
  /** Chip above the detail page heading (gone-home only) */
  statusLabel?: string;
  breeds: { slug: string; name: string }[];
  seoDescription: string;
  /** Card/lineup photo (listing cover; first gallery image for gone-home pups) */
  cover: Media;
  images: Media[];
  video: Media[];
  /** Gallery order as on the detail page (images and videos mixed) */
  media: Media[];
};

export const puppies: Puppy[] = ${ts(puppies)};

export const availablePuppies = puppies.filter((p) => p.status === "available");
export const goneHomePuppies = puppies.filter((p) => p.status === "gone-home");
export const getPuppy = (slug: string) => puppies.find((p) => p.slug === slug);
`);

// ---------- Testimonials ----------
const home = await read('home');
const testimonials = [];
for (const s of [home, await read('happy-families'), await read('how-it-works')]) {
  for (const m of s.matchAll(/"testimonial":\{/g)) {
    const t = jsonAt(s, m.index + '"testimonial":'.length);
    if (!testimonials.some((x) => x.id === t.id)) testimonials.push({ id: t.id, quote: t.quote, author: t.author, location: t.location, ...(t.media ? { media: media(t.media) } : {}) });
  }
  for (const m of s.matchAll(/"testimonials":\[/g)) {
    for (const t of jsonAt(s, m.index + '"testimonials":'.length))
      if (!testimonials.some((x) => x.id === t.id)) testimonials.push({ id: t.id, quote: t.quote, author: t.author, location: t.location, ...(t.media ? { media: media(t.media) } : {}) });
  }
}
const familyPhotos = valueAfter(await read('happy-families'), '"photos":').map(media);
console.log('testimonials', testimonials.length, 'family photos', familyPhotos.length);
await fs.writeFile('lib/data/testimonials.ts', `${header}
import type { Media } from "./puppies";

export type Testimonial = { id: string; quote: string; author: string; location: string; media?: Media };

export const testimonials: Testimonial[] = ${ts(testimonials)};

/** Photo wall on /happy-families */
export const familyPhotos: Media[] = ${ts(familyPhotos)};
`);

// ---------- FAQs ----------
const faqs = valueAfter(await read('faq'), '"faqs":').map((f) => ({ id: f.id, question: f.question, answer: f.answer }));
console.log('faqs', faqs.length);
await fs.writeFile('lib/data/faqs.ts', `${header}
export type Faq = { id: string; question: string; answer: string };

export const faqs: Faq[] = ${ts(faqs)};
`);

// ---------- Home sections (client-rendered ones carry a `section` object in the RSC) ----------
const sections = {};
for (const m of home.matchAll(/"section":\{/g)) {
  const sec = jsonAt(home, m.index + '"section":'.length);
  sections[sec.key] = { heading: sec.heading, body: sec.body, data: sec.data, media: (sec.media ?? []).map(media) };
}
// Chat props: "business":"…","greeting":"…","whatsappHref":"…","breeds":[…]
const at = home.indexOf('"business":');
const stringAfter = (k) => JSON.parse(home.slice(home.indexOf(k, at) + k.length).match(/^"(?:[^"\\]|\\.)*"/)[0]);
const chatProps = { business: stringAfter('"business":'), greeting: stringAfter('"greeting":'), breeds: valueAfter(home, '"breeds":', at) };
console.log('home sections', Object.keys(sections), 'chat breeds', chatProps.breeds?.length);
await fs.writeFile('lib/data/home.ts', `${header}
import type { Media } from "./puppies";

export type HomeSection = {
  heading: string;
  body: string;
  data: { ctaHref?: string; ctaLabel?: string; items?: { title: string; text: string }[]; mediaIds?: string[] };
  media: Media[];
};

/** Sections the original renders client-side: meet, journey, families */
export const homeSections: Record<"meet" | "journey" | "families", HomeSection> = ${ts(sections)};

/** WhatsApp phone mockup in "Your puppy journey" */
export const chat = ${ts({ business: chatProps.business, greeting: chatProps.greeting })};

/** Breed chips in the first chat bubble (available puppies per breed, most first) */
export const chatBreeds: { slug: string; name: string; n: number }[] = ${ts(chatProps.breeds)};
`);

// Home photo wall uses its own order (captioned photos first); append to home.ts
const homePhotos = valueAfter(home, '"photos":').map(media);
console.log('home photos', homePhotos.length, 'captioned', homePhotos.filter((p) => p.caption).length);
await fs.appendFile('lib/data/home.ts', `
/** Family photo wall on the home page (the first 8 are pinned up; the viewer pages through all) */
export const homePhotos: Media[] = ${ts(homePhotos)};
`);
